"""Isolated candidate workspace for agentic remediation.

Permission model (enforced here, not by prompts):
  * read   : files inside the inspected project (via the workspace copy); secrets never readable
  * write  : only inside the candidate workspace, only allow-listed config/manifest files, never lockfiles
             directly (they are regenerated by npm with scripts disabled), never secrets
  * shell  : no free-form shell. The only subprocesses are fixed argument lists:
             `npm install --package-lock-only --ignore-scripts` (registry metadata, no node_modules, no scripts),
             `git ls-remote` (read a remote tag -> SHA), and optional Docker test runs (see run_tests_sandboxed)
  * network: npm registry metadata, GitHub ls-remote, and the sandbox's own install step
  * original repository: never written here. `apply_to_original` is only reachable after explicit approval and
    refuses files that changed since the snapshot.

Every change is recorded as structured operations, so an approved subset can be replayed from the original
onto a fresh copy and re-diffed before anything is written to the real repository.
"""
from __future__ import annotations

import difflib
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from pydantic import BaseModel, Field

from scanners import CACHE_ROOT, _safe_env, git_show, is_git_repo, offline_mode, read_text, safe_run, validate_repo_path

WORKSPACE_ROOT = CACHE_ROOT / "workspaces"
COPY_SKIP_DIRS = {".git", "node_modules", ".scg_cache", ".venv", "venv", "__pycache__", "dist", "build", "coverage"}
SECRET_RE = re.compile(r"(^|/)(\.env[^/]*|.*\.pem|.*\.key|id_rsa[^/]*|id_ed25519[^/]*|\.npmrc|\.pypirc|\.netrc|"
                       r"credentials[^/]*|.*secret[^/]*|encryptionkeys/.*)$", re.I)
EDITABLE_RE = re.compile(r"^(package\.json|(.*/)?Dockerfile[^/]*|docker-compose[^/]*\.ya?ml|\.github/workflows/[^/]+\.ya?ml)$")
LOCKFILES = ("package-lock.json", "npm-shrinkwrap.json")
MAX_EDIT_BYTES = 200_000


class PermissionDenied(Exception):
    pass


def sha256(text: Optional[str]) -> Optional[str]:
    return None if text is None else hashlib.sha256(text.encode("utf-8")).hexdigest()


class FileChange(BaseModel):
    path: str
    before_sha: Optional[str]            # None = file did not exist
    after_sha: Optional[str]             # None = file deleted
    diff: str


class Change(BaseModel):
    """One agent action that modified the workspace."""
    change_id: str
    iteration: int
    tool: str
    args: Dict[str, Any]
    reason: str
    finding_ids: List[str] = Field(default_factory=list)
    ops: List[Dict[str, Any]] = Field(default_factory=list)   # replayable operations
    files: List[FileChange] = Field(default_factory=list)
    impact: str = "low"                  # low | high (high = could affect functionality; human must look)
    impact_reasons: List[str] = Field(default_factory=list)
    status: str = "applied"              # applied | rolled_back
    created_at: float = Field(default_factory=time.time)


class Workspace:
    def __init__(self, original: Path, label: str = "candidate") -> None:
        self.original = validate_repo_path(str(original))
        WORKSPACE_ROOT.mkdir(parents=True, exist_ok=True)
        for old in WORKSPACE_ROOT.iterdir():       # sweep our own abandoned copies (older than a day)
            try:
                if old.is_dir() and time.time() - old.stat().st_mtime > 86400:
                    shutil.rmtree(old, ignore_errors=True)
            except OSError:
                pass
        self.path = Path(tempfile.mkdtemp(prefix=f"{label}-", dir=WORKSPACE_ROOT)).resolve()
        self.snapshot: Dict[str, Optional[str]] = {}     # relpath -> sha256 of the original at copy time
        self.changes: List[Change] = []
        self._before: Dict[str, Dict[str, Optional[str]]] = {}   # change_id -> {path: content before}
        self._copy()

    # ---- setup / teardown ---------------------------------------------------- #
    def _copy(self) -> None:
        for root, dirs, files in os.walk(self.original):
            dirs[:] = [d for d in dirs if d not in COPY_SKIP_DIRS]
            rel_root = Path(root).relative_to(self.original)
            for f in files:
                src = Path(root) / f
                rel = (rel_root / f).as_posix()
                if src.is_symlink() or SECRET_RE.search(rel):
                    continue                    # never copy symlinks (escape risk) or secrets (incl. .npmrc)
                dst = self.path / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                try:
                    shutil.copy2(src, dst)
                except OSError:
                    continue
        for rel in ("package.json", *LOCKFILES):
            self.snapshot[rel] = sha256(read_text(self.original / rel, 60_000_000))

    def cleanup(self) -> None:
        shutil.rmtree(self.path, ignore_errors=True)

    # ---- permission-checked IO ----------------------------------------------- #
    def _resolve(self, rel: str, write: bool = False) -> Path:
        rel = (rel or "").replace("\\", "/")
        if rel.startswith("/") or re.match(r"^[A-Za-z]:", rel):
            raise PermissionDenied(f"absolute paths are not allowed: {rel}")
        if not rel or ".." in rel.split("/") or rel.startswith(".git/") or SECRET_RE.search(rel):
            raise PermissionDenied(f"access denied: {rel or '(empty path)'}")
        p = (self.path / rel).resolve()
        if not p.is_relative_to(self.path):
            raise PermissionDenied(f"path escapes the workspace: {rel}")
        if write:
            if Path(rel).name in LOCKFILES:
                raise PermissionDenied("lockfiles are regenerated by npm, never edited directly")
            if not EDITABLE_RE.match(rel):
                raise PermissionDenied(f"{rel} is not an editable config file (package.json, Dockerfile, "
                                       f"docker-compose, .github/workflows only)")
        return p

    def read(self, rel: str, limit: int = 2_000_000) -> Optional[str]:
        return read_text(self._resolve(rel), limit)

    def list_files(self, pattern: str = "", limit: int = 400) -> List[str]:
        out = []
        for p in sorted(self.path.rglob("*")):
            if p.is_file() and "node_modules" not in p.parts:
                rel = p.relative_to(self.path).as_posix()
                if not SECRET_RE.search(rel) and (not pattern or pattern in rel):
                    out.append(rel)
                    if len(out) >= limit:
                        break
        return out

    def search(self, needle: str, limit: int = 40) -> List[Dict[str, Any]]:
        if not needle or len(needle) > 200:
            raise ValueError("search needle must be 1-200 characters")
        hits = []
        for rel in self.list_files(limit=5000):
            if not re.search(r"\.(js|ts|mjs|cjs|jsx|tsx|json|ya?ml|md|sh)$|Dockerfile", rel):
                continue
            text = read_text(self.path / rel, 1_000_000) or ""
            for i, line in enumerate(text.splitlines(), 1):
                if needle in line:
                    hits.append({"file": rel, "line": i, "text": line.strip()[:200]})
                    if len(hits) >= limit:
                        return hits
        return hits

    # ---- change recording ---------------------------------------------------- #
    def _begin(self, change_id: str, paths: Sequence[str]) -> None:
        self._before[change_id] = {p: read_text(self.path / p, 60_000_000) for p in paths}

    def _finish(self, change: Change, paths: Sequence[str]) -> Change:
        before = self._before[change.change_id]
        for p in paths:
            old, new = before.get(p), read_text(self.path / p, 60_000_000)
            if old == new:
                continue
            diff = "".join(difflib.unified_diff((old or "").splitlines(True), (new or "").splitlines(True),
                                                f"a/{p}", f"b/{p}", n=3))
            if len(diff) > 120_000:
                diff = diff[:120_000] + f"\n... diff truncated ({len(diff)} bytes)\n"
            change.files.append(FileChange(path=p, before_sha=sha256(old), after_sha=sha256(new), diff=diff))
        self.changes.append(change)
        return change

    def rollback(self, change_id: str) -> Change:
        ch = next((c for c in self.changes if c.change_id == change_id), None)
        if ch is None or ch.status != "applied":
            raise ValueError(f"no applied change {change_id}")
        later = [c for c in self.changes if c.status == "applied" and c.created_at > ch.created_at
                 and {f.path for f in c.files} & {f.path for f in ch.files}]
        if later:
            raise ValueError(f"roll back {', '.join(c.change_id for c in later)} first (they touch the same files)")
        for path, content in self._before[change_id].items():
            target = self.path / path
            if content is None:
                target.unlink(missing_ok=True)
            else:
                target.write_text(content, encoding="utf-8")
        ch.status = "rolled_back"
        return ch

    # ---- operations (all replayable) ----------------------------------------- #
    def apply_ops(self, ops: Sequence[Dict[str, Any]], regen_lock: bool = True, log: Any = None) -> Dict[str, Any]:
        """Apply structured ops. Returns {"lock": {...}} describing lockfile regeneration."""
        dep_change = False
        for op in ops:
            kind = op["op"]
            if kind in ("set_dependency", "set_override", "remove_dependency", "delete_script"):
                manifest = json.loads(self.read("package.json") or "{}")
                if kind == "set_dependency":
                    section = op.get("section") or next((s for s in ("dependencies", "devDependencies", "optionalDependencies")
                                                         if op["name"] in (manifest.get(s) or {})), "dependencies")
                    manifest.setdefault(section, {})[op["name"]] = op["version"]
                    if op.get("move_from") and op["move_from"] != section:
                        (manifest.get(op["move_from"]) or {}).pop(op["name"], None)
                elif kind == "set_override":
                    manifest.setdefault("overrides", {})[op["name"]] = op["version"]
                elif kind == "remove_dependency":
                    for s in ("dependencies", "devDependencies", "optionalDependencies", "overrides"):
                        (manifest.get(s) or {}).pop(op["name"], None)
                elif kind == "delete_script":
                    (manifest.get("scripts") or {}).pop(op["name"], None)
                dep_change = dep_change or kind != "delete_script"
                self._resolve("package.json", write=True).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
            elif kind == "replace_text":
                p = self._resolve(op["path"], write=True)
                text = read_text(p, MAX_EDIT_BYTES)
                if text is None:
                    raise ValueError(f"{op['path']} does not exist or is too large to edit")
                if text.count(op["old"]) != 1:
                    raise ValueError(f"old text must occur exactly once in {op['path']} (found {text.count(op['old'])})")
                p.write_text(text.replace(op["old"], op["new"]), encoding="utf-8")
            elif kind == "restore_from_git":
                if not is_git_repo(self.original):
                    raise ValueError("original repository has no git history to restore from")
                content = git_show(self.original, op["ref"], op["path"])
                if content is None:
                    raise ValueError(f"{op['ref']}:{op['path']} not found in git history")
                target = (self.path / op["path"]).resolve()
                if not target.is_relative_to(self.path) or SECRET_RE.search(op["path"]):
                    raise PermissionDenied("restore target not allowed")
                target.write_text(content, encoding="utf-8")
            else:
                raise ValueError(f"unknown op {kind}")
        lock = {"regenerated": False, "reason": "no dependency change"}
        if dep_change and regen_lock:
            lock = self.regenerate_lockfile(log)
        return {"lock": lock}

    def has_lockfile(self) -> bool:
        return any((self.path / lf).exists() for lf in LOCKFILES)

    def regenerate_lockfile(self, log: Any = None, timeout: int = 420) -> Dict[str, Any]:
        """npm resolves the tree from registry metadata only: no tarballs, no node_modules, no scripts."""
        if not (self.original / "package-lock.json").exists() and not self.has_lockfile():
            return {"regenerated": False, "reason": "project commits no lockfile; package.json change only"}
        if offline_mode():
            return {"regenerated": False, "reason": "offline: npm cannot resolve the new tree", "error": True}
        if shutil.which("npm") is None:
            return {"regenerated": False, "reason": "npm not installed", "error": True}
        empty_rc = WORKSPACE_ROOT / "empty-npmrc"
        empty_rc.write_text("", encoding="utf-8")
        cmd = ["npm", "install", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund",
               "--legacy-peer-deps", f"--userconfig={empty_rc}", "--registry=https://registry.npmjs.org/"]
        try:
            res = safe_run(cmd, cwd=self.path, timeout=timeout)
        except (subprocess.SubprocessError, OSError) as exc:
            return {"regenerated": False, "reason": f"npm failed: {exc}", "error": True}
        shutil.rmtree(self.path / "node_modules", ignore_errors=True)   # must not exist; remove defensively
        if res.returncode != 0:
            return {"regenerated": False, "reason": f"npm exited {res.returncode}: {res.stderr.strip()[-300:]}", "error": True}
        return {"regenerated": True, "reason": "lockfile re-resolved from registry metadata (--package-lock-only --ignore-scripts)"}

    def record(self, change: Change, ops: List[Dict[str, Any]], log: Any = None) -> Tuple[Change, Dict[str, Any]]:
        paths = ["package.json", *LOCKFILES] + [op["path"] for op in ops if op.get("path")]
        paths = list(dict.fromkeys(paths))
        self._begin(change.change_id, paths)
        try:
            info = self.apply_ops(ops, log=log)
        except Exception:
            for path, content in self._before[change.change_id].items():      # leave no half-applied change
                if content is None:
                    (self.path / path).unlink(missing_ok=True)
                else:
                    (self.path / path).write_text(content, encoding="utf-8")
            raise
        change.ops = list(ops)
        return self._finish(change, paths), info

    # ---- diffs ------------------------------------------------------------------- #
    def diff_against_original(self) -> Dict[str, str]:
        """{path: unified diff} for every file that differs from the original repository."""
        out: Dict[str, str] = {}
        for rel in self.list_files(limit=20000):
            new = read_text(self.path / rel, 60_000_000)
            old = read_text(self.original / rel, 60_000_000)
            if new != old:
                out[rel] = "".join(difflib.unified_diff((old or "").splitlines(True), (new or "").splitlines(True),
                                                        f"a/{rel}", f"b/{rel}", n=3))
        return out

    def changed_contents(self) -> Dict[str, str]:
        return {rel: read_text(self.path / rel, 60_000_000) or "" for rel in self.diff_against_original()}


def git_ls_remote_sha(repo: str, ref: str, timeout: int = 30) -> Optional[str]:
    """Resolve owner/repo + tag/branch to a commit SHA (read-only, no clone)."""
    if offline_mode() or not re.fullmatch(r"[\w.-]+/[\w.-]+", repo) or not re.fullmatch(r"[\w./-]{1,100}", ref):
        return None
    try:
        res = safe_run(["git", "-c", "credential.helper=", "ls-remote", f"https://github.com/{repo}",
                        f"refs/tags/{ref}", f"refs/tags/{ref}^{{}}", f"refs/heads/{ref}"], timeout=timeout)
    except (subprocess.SubprocessError, OSError, FileNotFoundError):
        return None
    shas = {}
    for line in res.stdout.splitlines():
        sha, _, name = line.partition("\t")
        shas[name] = sha
    return shas.get(f"refs/tags/{ref}^{{}}") or shas.get(f"refs/tags/{ref}") or shas.get(f"refs/heads/{ref}")


def run_tests_sandboxed(ws: Workspace, timeout: int = 900) -> Dict[str, Any]:
    """Run the project's tests in Docker: install with scripts disabled, then `npm test` with --network none.

    Opt-in (SCG_SANDBOX_TESTS=1 or per session), because it executes the project's own test code. That code only
    ever runs inside a throwaway container: no host mounts besides a disposable copy, no network for the test
    step, no capabilities, memory/CPU/PID limits, and the copy is deleted afterwards.
    """
    if shutil.which("docker") is None:
        return {"status": "skipped", "reason": "docker is not installed"}
    manifest = json.loads(ws.read("package.json") or "{}")
    if not (manifest.get("scripts") or {}).get("test"):
        return {"status": "skipped", "reason": "package.json has no test script"}
    image = os.environ.get("SCG_SANDBOX_IMAGE", "node:20-bookworm-slim")
    copy = Path(tempfile.mkdtemp(prefix="tests-", dir=WORKSPACE_ROOT))
    try:
        shutil.copytree(ws.path, copy, dirs_exist_ok=True)
        common = ["docker", "run", "--rm", "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
                  "--memory", "2g", "--cpus", "2", "--pids-limit", "512", "-v", f"{copy}:/work", "-w", "/work",
                  "--user", f"{os.getuid()}:{os.getgid()}", "-e", "HOME=/tmp", "-e", "npm_config_cache=/tmp/.npm",
                  "-e", "NPM_CONFIG_IGNORE_SCRIPTS=true", "-e", "CI=true"]
        install = "ci" if (copy / "package-lock.json").exists() else "install"
        t0 = time.time()
        # install step: network only for the registry (explicit DNS: Docker's default resolver fails on some hosts);
        # scripts stay disabled, so no package code runs here. The test step below has no network at all.
        dns = [x for d in os.environ.get("SCG_SANDBOX_DNS", "1.1.1.1,8.8.8.8").split(",") if d.strip() for x in ("--dns", d.strip())]
        r1 = subprocess.run([*common, *dns, image, "npm", install, "--ignore-scripts", "--no-audit", "--no-fund",
                             "--fetch-timeout=60000", "--fetch-retries=1"],
                            capture_output=True, text=True, timeout=timeout, env=_safe_env(), stdin=subprocess.DEVNULL)
        if r1.returncode != 0:
            return {"status": "error", "phase": "install", "exit_code": r1.returncode,
                    "output": (r1.stdout + r1.stderr)[-2000:], "seconds": round(time.time() - t0, 1)}
        r2 = subprocess.run([*common, "--network", "none", image, "npm", "test", "--ignore-scripts"],
                            capture_output=True, text=True, timeout=timeout, env=_safe_env(), stdin=subprocess.DEVNULL)
        return {"status": "passed" if r2.returncode == 0 else "failed", "phase": "test", "exit_code": r2.returncode,
                "output": (r2.stdout + r2.stderr)[-3000:], "seconds": round(time.time() - t0, 1),
                "sandbox": f"{image}, --network none for tests, --cap-drop ALL, scripts disabled at install"}
    except subprocess.TimeoutExpired:
        return {"status": "error", "reason": f"timed out after {timeout}s"}
    finally:
        shutil.rmtree(copy, ignore_errors=True)
